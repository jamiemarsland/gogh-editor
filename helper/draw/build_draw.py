#!/usr/bin/env python3
"""
build_draw.py — gogh's section drawing, lifted out of the editor.

    python3 helper/draw/build_draw.py      (build.py runs it too)

The connector's widgets (MCP apps inside someone's chat) must show gogh's
real takes in the person's own words and colours, with no WordPress behind
them. The editor already draws its + Section previews in the browser from a
take's model (tplEls → buildCSS → makeNode), so this copies exactly those
functions — and everything they need — out of gogh-editor.js into one small
script, gogh-draw.js. It is rebuilt on every refresh, so the widget can never
drift from the editor: a take redrawn in the editor is redrawn in the chat.

What stays behind is stubbed below (STUBS): the editor's live state, the
theme's measured sizes, posts and shop sample drawing, embeds. The widget
supplies the theme itself (preset colours, sizes, fonts) as CSS variables.
"""

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import slice as S  # noqa: E402

ROOTS = ['fillTake', 'tplEls', 'buildCSS', 'makeNode', 'solve', 'TEMPLATES', 'VARIANTS',
         'diceFaces', 'templateByName', 'FONT_PAIRS',
         # the site connector's page panel also WRITES sections: the same
         # block markup the editor saves, with pictures from the site's pool
         'buildSectionBlocksV3', 'mediaPool', 'poolPick', 'tplBgFor']

# names the drawing references but a standalone page cannot (or need not) have
STUB_JS = r"""
  var cfg = window.GOGH_DRAW_CFG || {};
  // the theme's sizes, as the widget's own CSS declares them (Twenty
  // Twenty-Five's slugs); tplEls resolves the '__max' sentinel against these
  var FONT_SIZES = [
    { slug: 'small', size: '0.875rem' }, { slug: 'medium', size: '1.125rem' },
    { slug: 'large', size: '1.375rem' }, { slug: 'x-large', size: '2rem' },
    { slug: 'xx-large', size: '3rem' }
  ];
  function fontSizes() { return FONT_SIZES; }
  // a section drawn outside the editor has no neighbours: no dividers,
  // transitions or drags to account for (the editor's sectionOpts reads them)
  function sectionOpts(sec) {
    return { bg: sec.bg, bgA: sec.bgA != null ? sec.bgA : null, fill: !!sec.fill, divider: sec.divider, bgImage: sec.bgImage,
      bgVideo: sec.bgVideo || null, m: sec.m || null, bgPos: sec.bgPos || null, fx: sec.fx || null };
  }
  function embedNode() { var d = document.createElement('div'); d.className = 'gogh-embed-stub'; return d; }
  function videoNode() { var d = document.createElement('div'); d.className = 'gogh-video-stub'; return d; }
  function composePosts() { return ''; }
  function postsPreviewHTML() { return ''; }
  function samplePosts() { return []; }
  function postsDefaults() { return {}; }
  function shopDefaults() { return {}; }
  function composeShop() { return ''; }
  function shopSampleHTML() { return ''; }
"""
STUBS = set(re.findall(r'(?:function|var) (\w+)', STUB_JS))

EXPORTS = ROOTS + ['W', 'DISPLAY_FS']


def build():
    lines = S.SRC.read_text(encoding='utf-8').split('\n')
    D = S.decls(lines)
    missing = [r for r in ROOTS if r not in D]
    if missing:
        sys.exit('build_draw: the editor no longer declares ' + ', '.join(missing))
    want = S.closure(lines, D, ROOTS, STUBS)
    ranges = sorted({D[n] for n in want})
    parts, last = [], -1
    for a, b in ranges:
        if a <= last:  # a multi-name var line already taken
            continue
        parts.append('\n'.join(lines[a:b + 1]))
        last = b
    body = '\n'.join(parts)
    exports = ', '.join(f'{n}: {n}' for n in EXPORTS)
    out = ('/* gogh-draw.js — GENERATED by helper/draw/build_draw.py from gogh-editor.js.\n'
           ' * Do not edit: change the editor and run python3 helper/refresh.py. */\n'
           '(function () {\n  \'use strict\';\n' + STUB_JS + body +
           f'\n  window.goghDraw = {{ {exports} }};\n}})();\n')
    dest = HERE / 'gogh-draw.js'
    dest.write_text(out, encoding='utf-8')
    # the plugin's own copy, for the site connector's page panel (helper/ is
    # not part of every install's needs, connector/ is)
    (HERE.parents[1] / 'connector' / 'gogh-draw.js').write_text(out, encoding='utf-8')
    return dest, len(want), len(out)


def picker(draw_js=None):
    """The hero picker widget: hero-picker.html with the drawing and the
    theme rules inlined — one self-contained page, as an MCP app must be."""
    if draw_js is None:
        draw_js = (HERE / 'gogh-draw.js').read_text(encoding='utf-8')
    page = (HERE / 'hero-picker.html').read_text(encoding='utf-8')
    theme = (HERE / 'theme.css').read_text(encoding='utf-8')
    page = page.replace('__THEME_CSS__', theme).replace('__DRAW_JS__', draw_js.replace('</script', '<\\/script'))
    (HERE / 'hero-picker.built.html').write_text(page, encoding='utf-8')
    return page


def faces():
    """Each opening family's take names, for the worker's check and rules."""
    lines = S.SRC.read_text(encoding='utf-8').split('\n')
    D = S.decls(lines)
    a, b = D['VARIANTS']
    block = '\n'.join(lines[a:b + 1])
    out = {}
    for fam, take in re.findall(r"\{ name: '([^']+)', take: '([^']+)'", block):
        out.setdefault(fam, ['The original']).append(take)
    return out


if __name__ == '__main__':
    dest, n, size = build()
    print(f'build_draw: {dest.name} {size:,} bytes, {n} declarations from the editor')
    print(f'build_draw: hero-picker.built.html {len(picker()):,} bytes')
