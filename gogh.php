/**
 * v1 posture: the front-end admin bar shows ONE way to edit — gogh. The
 * native entry points (Site Editor, Edit Page, +New, comments) return with
 * the experiments flag for the curious.
 */
add_action( 'admin_bar_menu', function ( $bar ) {
	if ( is_admin() ) {
		return;
	}
	// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only mode check
	if ( isset( $_GET['gogh-experiments'] ) || isset( $_GET['gogh-test'] ) ) {
		return;
	}
	// the front-end bar is a CREATION surface, not a dashboard: the WP
	// logo menu, update counters and search live in wp-admin where they
	// belong ("how can we make this nicer / simpler for folks")
	foreach ( array( 'site-editor', 'edit-site', 'customize', 'comments', 'new-content', 'edit', 'wp-logo', 'updates', 'search' ) as $id ) {
		$bar->remove_node( $id );
	}
	// products: a tiny layout menu — pick one of a few fixed layouts,
	// never edit a template
	if ( is_singular( 'product' ) && function_exists( 'gogh_product_layouts' ) ) {
		$pid = get_queried_object_id();
		if ( $pid && current_user_can( 'edit_post', $pid ) ) {
			$current = get_page_template_slug( $pid );
			$layouts = gogh_product_layouts();
			if ( ! isset( $layouts[ $current ] ) ) {
				$current = '';
			}
			$bar->add_node( array(
				'id'    => 'gogh-product-layout',
				'title' => '🎨 Product layout',
			) );
			foreach ( $layouts as $slug => $label ) {
				$bar->add_node( array(
					'id'     => 'gogh-product-layout-' . ( $slug ? $slug : 'classic' ),
					'parent' => 'gogh-product-layout',
					'title'  => ( $slug === $current ? '✓ ' : '' ) . $label,
					'href'   => wp_nonce_url( admin_url( 'admin-post.php?action=gogh_product_layout&id=' . $pid . '&layout=' . rawurlencode( $slug ) ), 'gogh_product_layout_' . $pid ),
				) );
			}
			// one more click stamps the catalogue — individual products can
			// still be changed afterwards, one at a time
			$current_label = preg_replace( '/\s+—.*$/u', '', $layouts[ $current ] );
			$bar->add_node( array(
				'id'     => 'gogh-product-layout-all',
				'parent' => 'gogh-product-layout',
				'title'  => sprintf( __( 'Apply “%s” to all products', 'gogh-editor' ), $current_label ),
				'href'   => wp_nonce_url( admin_url( 'admin-post.php?action=gogh_product_layout_all&id=' . $pid ), 'gogh_product_layout_all' ),
			) );
		}
	}
	// one thing beginners DO need from the old menu: a new page — and it
	// goes straight into gogh
	// which room is this? posts and the blog index are the WRITING room;
	// everything else is the design studio — the bar only offers the verbs
	// that belong to the room ("this is really the site designer")
	$is_post_room = is_singular( 'post' ) || is_home();
	$has_blog     = 'posts' === get_option( 'show_on_front' ) || (int) get_option( 'page_for_posts' ) > 0;
	$plus         = '<svg class="gogh-ab-ic" width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.4" stroke-linecap="round"><path d="M12 5v14M5 12h14"/></svg>';
	$pen2         = '<svg class="gogh-ab-ic" width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.1" stroke-linecap="round" stroke-linejoin="round"><path d="M12 20h9"/><path d="M16.5 3.5a2.1 2.1 0 0 1 3 3L7 19l-4 1 1-4Z"/></svg>';
	$new_page = array(
		'id'    => 'gogh-new-page',
		'title' => $plus . 'New page',
		'href'  => wp_nonce_url( admin_url( 'admin-post.php?action=gogh_new_page' ), 'gogh_new_page' ),
	);
	$new_post = array(
		'id'    => 'gogh-write',
		'title' => $pen2 . 'New post',
		'href'  => add_query_arg( 'gogh-new-post', '1', home_url( '/' ) ),
		'meta'  => array( 'title' => 'A clean canvas and space to think' ),
	);
	if ( $is_post_room && $has_blog && current_user_can( 'edit_posts' ) ) {
		$bar->add_node( $new_post );
	}
	// New page rides only in the site menu now ("maybe lets remove this") —
	// the bar on a page keeps a single door: Edit with gogh
	// the safety net: both creations live quietly under the site name, so
	// nothing is ever unreachable from the wrong room
	if ( current_user_can( 'publish_pages' ) ) {
		$bar->add_node( array_merge( $new_page, array( 'id' => 'gogh-new-page-menu', 'parent' => 'site-name' ) ) );
	}
	if ( $has_blog && current_user_can( 'edit_posts' ) ) {
		$bar->add_node( array_merge( $new_post, array( 'id' => 'gogh-write-menu', 'parent' => 'site-name' ) ) );
	}
	// wp-admin plumbing leaves the site menu — Dashboard stays as the
	// escape hatch; Plugins and Themes are not site-making
	foreach ( array( 'plugins', 'themes', 'widgets', 'menus', 'appearance' ) as $noise ) {
		$bar->remove_node( $noise );
	}
	// the edit/exit landmark closes the cluster: re-adding sends it last
	$edit_node = $bar->get_node( 'gogh-edit' );
	if ( $edit_node ) {
		$bar->remove_node( 'gogh-edit' );
		$bar->add_node( (array) $edit_node );
	}
}, 999 );

