	wp_register_script(
		'gogh-block',
		plugins_url( 'gogh-block.js', __FILE__ ),
		array( 'wp-blocks', 'wp-element', 'wp-block-editor' ),
		'0.99.349-chrome',
		true
	);
	register_block_type( 'gogh/section', array(
		'editor_script'   => 'gogh-block',
		// SPIKE (attrs-as-truth): v3 sections store { model, cssT } as block
		// attributes and derive presentation here. Legacy (v2) sections carry
		// no attributes and pass through verbatim — fully static, unchanged.
		'render_callback' => 'gogh_render_section',
	) );
} );

/**
 * SPIKE: emit a v3 section. PHP does scoping + emission ONLY — the layout
 * engine stays in the editor; cssT arrives fully compiled with a GOGHSCOPE
 * placeholder.
 *
 * SECURITY: block attributes are writable by users WITHOUT unfiltered_html
 * (KSES does not police attribute JSON), so everything emitted from them is
 * sanitized here: the scope is slug-cast and the CSS may not contain the
 * characters that could open an element or comment. Without this, cssT would
 * be a stored-XSS bypass around KSES.
 */
function gogh_css_from_attrs( $attrs ) {
	if ( empty( $attrs['cssT'] ) || empty( $attrs['scope'] ) ) {
		return '';
	}
	$scope = preg_replace( '/[^a-z0-9-]/', '', (string) $attrs['scope'] );
	if ( '' === $scope ) {
		return '';
	}
	$css = str_replace( 'GOGHSCOPE', $scope, (string) $attrs['cssT'] );
	// CSS never needs these characters; their absence makes markup injection impossible
	return str_replace( array( '<', '>', '\\' ), '', $css );
}

/**
 * When KSES strips a baked <style> TAG it leaves the CSS behind as loose
 * text. Our stylesheets all open with a sentinel comment and never contain
 * '<', so the residue is precisely delimited and safe to sweep.
 */
function gogh_sweep_css_residue( $html ) {
	return preg_replace( '/\/\* generated by gogh \*\/[^<]*/', '', $html );
}

function gogh_render_section( $attrs, $content ) {
	$attrs = is_array( $attrs ) ? $attrs : array();
	$css   = gogh_css_from_attrs( $attrs );
	if ( '' === $css ) {
		return $content; // legacy v2: static markup is already complete
	}
	if ( false === strpos( $content, 'class="gogh-style"' ) ) {
		$content = gogh_sweep_css_residue( $content );
		$style   = '<style class="gogh-style">' . $css . '</style>';
		$out     = preg_replace( '/(<div class="wp-block-gogh-section[^"]*">)/', '$1' . $style, $content, 1, $n );
		$content = $n ? $out : $style . $content;
	}
	return gogh_inject_experiences( $attrs, gogh_faq_schema( $attrs ) . $content );
}

/**
 * FAQ sections carry their questions as DATA in the model — so the render
 * can speak schema.org fluently: one FAQPage JSON-LD script per FAQ
 * section, generated fresh on every render (never stored, never kses'd).
 */
function gogh_faq_schema( $attrs ) {
	$els = isset( $attrs['model']['elements'] ) && is_array( $attrs['model']['elements'] )
		? $attrs['model']['elements'] : array();
	$qa = array();
	foreach ( $els as $e ) {
		if ( empty( $e['faq'] ) || ! is_array( $e['faq'] ) ) {
			continue;
		}
		foreach ( $e['faq'] as $item ) {
			if ( empty( $item['q'] ) || empty( $item['a'] ) ) {
				continue;
			}
			$qa[] = array(
				'@type'          => 'Question',
				'name'           => wp_strip_all_tags( $item['q'] ),
				'acceptedAnswer' => array(
					'@type' => 'Answer',
					'text'  => wp_strip_all_tags( $item['a'] ),
				),
			);
		}
	}
	if ( ! $qa ) {
		return '';
	}
	$schema = array(
		'@context'   => 'https://schema.org',
		'@type'      => 'FAQPage',
		'mainEntity' => $qa,
	);
	return '<script type="application/ld+json">' . wp_json_encode( $schema, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE ) . '</script>';
}

/**
 * Experiences: stored markup carries only a plain link (kses-safe, and the
 * plugin-off fallback). At render time it becomes a sandboxed iframe. The
 * src is NEVER taken from attributes — only the attachment ID is, and the
 * URL is resolved server-side after checking the attachment really is an
 * uploaded text/html file (uploads of which are capability-gated below).
 * allow-scripts WITHOUT allow-same-origin = opaque origin: the uploaded
 * code cannot read cookies or reach the embedding page.
 */
function gogh_inject_experiences( $attrs, $content ) {
	$els = isset( $attrs['model']['elements'] ) && is_array( $attrs['model']['elements'] )
		? $attrs['model']['elements'] : array();
	foreach ( $els as $i => $e ) {
		if ( empty( $e['type'] ) || 'exp' !== $e['type'] || empty( $e['expId'] ) ) {
			continue;
		}
		$id = intval( $e['expId'] );
		if ( $id <= 0 || 'text/html' !== get_post_mime_type( $id ) ) {
			continue;
		}
		$src = wp_get_attachment_url( $id );
		if ( ! $src ) {
			continue;
		}
		$iframe  = '<iframe src="' . esc_url( $src ) . '" sandbox="allow-scripts" title="Interactive experience" loading="lazy" style="width:100%;height:100%;border:0;display:block"></iframe>';
		// the class list gains render-time extras (layout support), so match
		// by our two authored classes rather than the exact attribute value
		$content = preg_replace_callback(
			'/(<div class="[^"]*\bgogh-el-' . ( $i + 1 ) . '\b[^"]*\bgogh-exp\b[^"]*">).*?<\/div>/s',
			function ( $m ) use ( $iframe ) {
				return $m[1] . $iframe . '</div>';
			},
			$content,
			1
		);
	}
	return $content;
}

