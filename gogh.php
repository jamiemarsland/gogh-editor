/**
 * Live-preview renderer: the core block-renderer returns bare markup with
 * none of the per-instance layout CSS (nav flex rules, container gaps), so
 * header/footer previews looked broken. This renders markup the way a real
 * page does and returns the generated styles + the block stylesheets the
 * markup needs.
 */
add_action( 'rest_api_init', function () {
	register_rest_route( 'gogh/v1', '/render', array(
		'methods'             => 'POST',
		'permission_callback' => function () {
			return current_user_can( 'edit_posts' );
		},
		'callback'            => function ( $req ) {
			$content = (string) $req->get_param( 'content' );
			$html    = do_blocks( $content );
			// BOTH style-engine stores: with the Gutenberg plugin active its
			// namespaced store holds the layout/element rules and core's sits
			// empty — querying only core lost every justify/gap/colour rule
			// ("quite a few header layouts look a little broken")
			$css = '';
			if ( function_exists( 'gutenberg_style_engine_get_stylesheet_from_context' ) ) {
				$css .= (string) gutenberg_style_engine_get_stylesheet_from_context( 'block-supports' );
			}
			if ( function_exists( 'wp_style_engine_get_stylesheet_from_context' ) ) {
				$css .= (string) wp_style_engine_get_stylesheet_from_context( 'block-supports' );
			}
			$hrefs = array();
			$walk  = function ( $blocks ) use ( &$walk, &$hrefs ) {
				foreach ( $blocks as $b ) {
					if ( ! empty( $b['blockName'] ) ) {
						$bt = WP_Block_Type_Registry::get_instance()->get_registered( $b['blockName'] );
						if ( $bt ) {
							foreach ( (array) $bt->style_handles as $h ) {
								if ( $h && wp_style_is( $h, 'registered' ) ) {
									$obj = wp_styles()->registered[ $h ];
									if ( ! empty( $obj->src ) ) {
										$src = ( 0 === strpos( $obj->src, 'http' ) ) ? $obj->src : site_url( $obj->src );
										$hrefs[ $h ] = add_query_arg( 'ver', $obj->ver ? $obj->ver : get_bloginfo( 'version' ), $src );
									}
								}
							}
						}
					}
					if ( ! empty( $b['innerBlocks'] ) ) {
						$walk( $b['innerBlocks'] );
					}
				}
			};
			$walk( parse_blocks( $content ) );
			return array(
				'html'   => $html,
				'css'    => $css,
				'styles' => array_values( $hrefs ),
			);
		},
	) );
} );

/**
 * Editor contexts (post editor, site editor, pattern previews): a gogh
 * section's grid uses cqw units against the .gogh-wrap container. In
 * shrink-to-fit preview wrappers, inline-size containment collapses the wrap
 * to width 0 — every saved section needs the same width floor there.
 */
add_action( 'enqueue_block_assets', function () {
	if ( ! is_admin() ) {
		return;
	}
	wp_register_style( 'gogh-editor-base', false, array(), '0.99.349-chrome' );
	wp_enqueue_style( 'gogh-editor-base' );
	wp_add_inline_style( 'gogh-editor-base',
		'.gogh-wrap { min-width: 100%; margin-block: 0 !important; }' .
		'.gogh-section > .wp-block-group { padding: 0 !important; box-sizing: border-box; }' .
		'.gogh-section > * { box-sizing: border-box; }' .
		// splashes are core blocks wearing gogh classes — without their
		// presentation the editor shows a wall as a stack and a carousel as
		// a pile ("kinda breaking in the gutenberg view"). Same CSS, both rooms.
		gogh_splash_css() .
		// the editor prefixes theme rules with .editor-styles-wrapper, which
		// out-specifies the shared height rule (its height:auto won, so the
		// break showed the photo's full natural height) — re-state the window
		// at editor specificity
		'.editor-styles-wrapper figure.wp-block-image.gogh-splash-break img { height: min(66vh, 640px); }' .
		// buttons: on the canvas they FILL their grid cell (width/height 100%
		// from the section CSS) — in Gutenberg, where container units can
		// resolve oddly (Playground especially), that fill balloons a button
		// into a wrapping blob. Natural pill size in the editor is faithful
		// AND unbreakable.
		'.editor-styles-wrapper .gogh-section .wp-block-button, .editor-styles-wrapper .gogh-section .wp-block-button__link { width: auto !important; height: auto !important; min-height: 0 !important; white-space: nowrap; }'
	);
} );

