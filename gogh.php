/**
 * Pattern previews: core's block-renderer returns markup WITHOUT the
 * per-instance layout CSS (flex/grid/gap rules the style engine generates
 * during render), so grids collapse into a squished huddle in the picker.
 * This route renders a pattern and hands back that CSS alongside the markup.
 */
add_action( 'rest_api_init', function () {
	register_rest_route( 'gogh/v1', '/pattern', array(
		'methods'             => 'GET',
		'permission_callback' => function () {
			return current_user_can( 'edit_posts' );
		},
		'args'                => array( 'slug' => array( 'required' => true, 'type' => 'string' ) ),
		'callback'            => function ( $req ) {
			$pat = WP_Block_Patterns_Registry::get_instance()->get_registered( (string) $req['slug'] );
			if ( ! $pat ) {
				return new WP_Error( 'gogh_no_pattern', __( 'Unknown pattern.', 'gogh-editor' ), array( 'status' => 404 ) );
			}
			$html = do_blocks( (string) $pat['content'] );
			$css  = function_exists( 'wp_style_engine_get_stylesheet_from_context' )
				? wp_style_engine_get_stylesheet_from_context( 'block-supports' )
				: '';
			return array( 'rendered' => $html, 'css' => $css );
		},
	) );
} );

/**
 * Last line of defence for site chrome: gogh's editor UI classes must never
 * appear in STORED template parts or navigation menus. If they do, some
 * DOM-derived markup is being saved by mistake (this once replaced a header
 * with its own rendered DOM, add-page buttons included) — refuse the write
 * loudly instead of corrupting every page on the site.
 */
add_action( 'rest_api_init', function () {
	$guard = function ( $prepared ) {
		$c = is_object( $prepared ) && isset( $prepared->post_content ) ? $prepared->post_content : '';
		foreach ( array( 'gogh-navadd', 'gogh-pendbar', 'gogh-storedrm', 'gogh-convertbtn', 'gogh-selbox', 'data-gogh' ) as $mark ) {
			if ( false !== strpos( $c, $mark ) ) {
				return new WP_Error(
					'gogh_artifact_in_chrome',
					__( 'gogh blocked this save: editor-only markup was about to be stored in site chrome.', 'gogh-editor' ),
					array( 'status' => 400 )
				);
			}
		}
		return $prepared;
	};
	add_filter( 'rest_pre_insert_wp_template_part', $guard );
	add_filter( 'rest_pre_insert_wp_navigation', $guard );
} );

