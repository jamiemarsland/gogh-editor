/**
 * SPIKE variant B: rebake. On every save — by anyone, including users whose
 * content KSES just filtered — regenerate the baked <style> inside each v3
 * section from its attributes. The plugin authors these bytes server-side,
 * so the saver's capabilities are irrelevant; deactivation keeps the look.
 * ADOPTED as production behaviour (variant B won the matrix): default ON,
 * gogh_rebake_enabled filter remains as the escape hatch.
 */
function gogh_rebake_post_data( $data ) {
	if ( ! apply_filters( 'gogh_rebake_enabled', true ) ) {
		return $data;
	}
	if ( empty( $data['post_content'] ) || false === strpos( $data['post_content'], 'wp:gogh/section' ) ) {
		return $data;
	}
	$content = wp_unslash( $data['post_content'] );
	$blocks  = parse_blocks( $content );
	$changed = false;
	foreach ( $blocks as &$b ) {
		if ( 'gogh/section' !== $b['blockName'] || empty( $b['attrs'] ) ) {
			continue;
		}
		$css = gogh_css_from_attrs( $b['attrs'] );
		if ( '' === $css || false !== strpos( (string) $b['innerHTML'], 'class="gogh-style"' ) ) {
			continue;
		}
		$style = '<style class="gogh-style">' . $css . '</style>';
		foreach ( array( 'innerHTML', 'innerContent' ) as $k ) {
			if ( 'innerContent' === $k ) {
				foreach ( $b['innerContent'] as &$chunk ) {
					if ( is_string( $chunk ) && false !== strpos( $chunk, 'wp-block-gogh-section' ) ) {
						$chunk   = gogh_sweep_css_residue( $chunk );
						$chunk   = preg_replace( '/(<div class="wp-block-gogh-section[^"]*">)/', '$1' . $style, $chunk, 1 );
						$changed = true;
						break;
					}
				}
			} else {
				$b[ $k ] = gogh_sweep_css_residue( (string) $b[ $k ] );
				$b[ $k ] = preg_replace( '/(<div class="wp-block-gogh-section[^"]*">)/', '$1' . $style, $b[ $k ], 1 );
			}
		}
	}
	unset( $b );
	if ( $changed ) {
		$data['post_content'] = wp_slash( serialize_blocks( $blocks ) );
	}
	return $data;
}
add_filter( 'wp_insert_post_data', 'gogh_rebake_post_data', 20 );

/**
 * ✦ Answer-ready — the page's meaning, emitted as JSON-LD.
 *
 * Schema is to meaning what cssT is to looks: a second projection of the
 * same section model. The designer composed an FAQ accordion, so the model
 * literally stores the questions and answers — no inference, no settings
 * screen. On save the graph is computed once into _gogh_schema; wp_head
 * just echoes the cached bytes.
 *
 * Guardrails: emit only what the design states. An FAQPage needs a real
 * question AND answer; anything incomplete simply doesn't emit. Yoast and
 * RankMath own the graph when they're active, and gogh_schema_enabled is
 * the escape hatch.
 */
function gogh_schema_collect_els( $els, &$faq, &$first_para ) {
	foreach ( (array) $els as $e ) {
		if ( ! empty( $e['faq'] ) && is_array( $e['faq'] ) ) {
			foreach ( $e['faq'] as $item ) {
				$q = trim( wp_strip_all_tags( (string) ( $item['q'] ?? '' ) ) );
				$a = trim( wp_strip_all_tags( (string) ( $item['a'] ?? '' ) ) );
				if ( '' !== $q && '' !== $a ) {
					$faq[] = array( 'q' => $q, 'a' => $a );
				}
			}
		}
		if ( '' === $first_para && ( $e['type'] ?? '' ) === 'para' && ! empty( $e['text'] ) ) {
			$first_para = trim( wp_strip_all_tags( (string) $e['text'] ) );
		}
		if ( ! empty( $e['kids'] ) && is_array( $e['kids'] ) ) {
			gogh_schema_collect_els( $e['kids'], $faq, $first_para );
		}
	}
}

function gogh_schema_build( $post ) {
	$faq        = array();
	$first_para = '';
	foreach ( parse_blocks( $post->post_content ) as $b ) {
		if ( 'gogh/section' !== ( $b['blockName'] ?? '' ) ) {
			continue;
		}
		if ( ! empty( $b['attrs']['model']['elements'] ) ) {
			gogh_schema_collect_els( $b['attrs']['model']['elements'], $faq, $first_para );
		} elseif ( ! empty( $b['innerHTML'] ) &&
			preg_match( '/<script type="application\/json" class="gogh-model">(.*?)<\/script>/s', $b['innerHTML'], $m ) ) {
			// legacy v2 sections carry the model in a script tag, not attrs
			$j = json_decode( $m[1], true );
			if ( ! empty( $j['elements'] ) ) {
				gogh_schema_collect_els( $j['elements'], $faq, $first_para );
			}
		}
	}
	$home = home_url( '/' );
	$org  = array(
		'@type' => 'Organization',
		'@id'   => $home . '#org',
		'name'  => get_bloginfo( 'name' ),
		'url'   => $home,
	);
	$logo_id = get_theme_mod( 'custom_logo' );
	if ( $logo_id ) {
		$logo = wp_get_attachment_image_url( $logo_id, 'full' );
		if ( $logo ) {
			$org['logo'] = $logo;
		}
	}
	if ( 'post' === $post->post_type ) {
		// Write posts are pure core blocks (deactivation-safe by design), so
		// the Article's facts come from WordPress itself — headline, dates,
		// author, image. Nothing here is inferred; every field is a fact WP
		// already asserts about the post.
		$page = array(
			'@type'            => 'Article',
			'headline'         => mb_substr( get_the_title( $post ), 0, 110 ),
			'url'              => get_permalink( $post ),
			'mainEntityOfPage' => get_permalink( $post ),
			'datePublished'    => get_post_time( 'c', true, $post ),
			'dateModified'     => get_post_modified_time( 'c', true, $post ),
			'publisher'        => array( '@id' => $home . '#org' ),
		);
		$author = get_the_author_meta( 'display_name', $post->post_author );
		if ( $author ) {
			$page['author'] = array( '@type' => 'Person', 'name' => $author );
		}
		$img = get_the_post_thumbnail_url( $post, 'full' );
		if ( ! $img && preg_match( '/<img[^>]+src="([^"]+)"/', $post->post_content, $im ) ) {
			$img = $im[1]; // the first break/splash image stands in for a missing featured image
		}
		if ( $img ) {
			$page['image'] = $img;
		}
		// the writer's own words WIN: the excerpt (edited on the search-
		// preview card) beats every derived fallback
		$hand = trim( wp_strip_all_tags( (string) $post->post_excerpt ) );
		$desc = '' !== $hand ? $hand
			: ( '' !== $first_para ? $first_para
				: wp_trim_words( wp_strip_all_tags( strip_shortcodes( $post->post_content ) ), 28, '…' ) );
		if ( $desc ) {
			$page['description'] = mb_substr( $desc, 0, '' !== $hand ? 300 : 160 );
		}
	} else {
		$page = array(
			'@type'        => 'WebPage',
			'name'         => get_the_title( $post ),
			'url'          => get_permalink( $post ),
			'dateModified' => get_post_modified_time( 'c', true, $post ),
			'publisher'    => array( '@id' => $home . '#org' ),
		);
		// same law as posts: the writer's own words WIN — the excerpt
		// (edited on the search-preview card) beats the derived first line
		$hand = trim( wp_strip_all_tags( (string) $post->post_excerpt ) );
		$desc = '' !== $hand ? $hand : $first_para;
		if ( '' !== $desc ) {
			$page['description'] = mb_substr( $desc, 0, '' !== $hand ? 300 : 160 );
		}
	}
	$graph = array( $org, $page );
	if ( $faq ) {
		$graph[] = array(
			'@type'      => 'FAQPage',
			'mainEntity' => array_map( function ( $p ) {
				return array(
					'@type'          => 'Question',
					'name'           => $p['q'],
					'acceptedAnswer' => array(
						'@type' => 'Answer',
						'text'  => $p['a'],
					),
				);
			}, $faq ),
		);
	}
	return apply_filters( 'gogh_schema', array( '@context' => 'https://schema.org', '@graph' => $graph ), $post );
}

add_action( 'save_post', function ( $post_id, $post ) {
	if ( wp_is_post_revision( $post_id ) || wp_is_post_autosave( $post_id ) ) {
		return;
	}
	if ( ! in_array( $post->post_type, array( 'page', 'post' ), true ) ) {
		return;
	}
	// pages carry meaning in their section models — no sections, no graph.
	// POSTS always emit: the Article's facts (title, dates, author, image)
	// are WordPress's own assertions, true whether or not the words were
	// written in gogh's Write room ("does this work with write?").
	if ( 'page' === $post->post_type && ! has_block( 'gogh/section', $post ) ) {
		delete_post_meta( $post_id, '_gogh_schema' );
		return;
	}
	if ( 'publish' !== $post->post_status && 'post' === $post->post_type && ! has_block( 'gogh/section', $post ) ) {
		return; // drafts keep whatever they had; the graph lands on publish
	}
	$graph = gogh_schema_build( $post );
	if ( $graph ) {
		// HEX_TAG keeps </script> impossible inside the JSON; wp_slash
		// survives the meta layer's stripslashes so \u escapes hold
		update_post_meta( $post_id, '_gogh_schema', wp_slash( wp_json_encode( $graph, JSON_UNESCAPED_SLASHES | JSON_HEX_TAG ) ) );
	} else {
		delete_post_meta( $post_id, '_gogh_schema' );
	}
}, 10, 2 );

