/**
 * Starter sites: whole sites (pages + menu + front page) shipped as
 * manifests + block-markup files under starters/<slug>/. Pages register as
 * hidden patterns so the preview route can render them; applying a starter
 * is one REST call that trashes current pages (restorable), creates the new
 * set, rebuilds the menu, and wires the front and posts pages.
 */
// the test fixture recreates itself: it reads as junk in the Pages list
// and keeps getting trashed (twice now). Visiting any page with
// ?gogh-test=1 restores or rebuilds it from the bundled copy.
add_action( 'init', function () {
	if ( ! isset( $_GET['gogh-test'] ) || ! current_user_can( 'edit_posts' ) ) {
		return;
	}
	$fixture = get_page_by_path( 'gogh-test-fixture' );
	if ( $fixture && 'publish' === $fixture->post_status ) {
		return;
	}
	if ( $fixture && 'trash' === $fixture->post_status ) {
		wp_untrash_post( $fixture->ID );
		wp_update_post( array( 'ID' => $fixture->ID, 'post_status' => 'publish', 'post_name' => 'gogh-test-fixture' ) );
		return;
	}
	$file = __DIR__ . '/tests-fixture.html';
	if ( is_readable( $file ) ) {
		wp_insert_post( array(
			'post_type'    => 'page',
			'post_status'  => 'publish',
			'post_title'   => 'gogh test fixture',
			'post_name'    => 'gogh-test-fixture',
			'post_content' => file_get_contents( $file ),
		) );
	}
} );

// gogh write: a clean canvas and space to think. ?gogh-new-post creates
// a draft and lands the writer straight on the front-end surface;
// ?gogh-write=1 on any editable post enables the mode.
add_action( 'template_redirect', function () {
	if ( ! isset( $_GET['gogh-new-post'] ) || ! current_user_can( 'edit_posts' ) ) {
		return;
	}
	$id = wp_insert_post( array(
		'post_type'    => 'post',
		'post_status'  => 'draft',
		'post_title'   => '',
		// wp_insert_post refuses a FULLY empty post — one blank paragraph
		// is the difference between a canvas and an error
		'post_content' => '<!-- wp:paragraph --><p></p><!-- /wp:paragraph -->',
	) );
	if ( $id && ! is_wp_error( $id ) ) {
		wp_safe_redirect( add_query_arg( array( 'p' => $id, 'preview' => 'true', 'gogh-write' => '1' ), home_url( '/' ) ) );
		exit;
	}
} );
add_action( 'wp_enqueue_scripts', function () {
	if ( ! isset( $_GET['gogh-write'] ) || ! is_singular( 'post' ) ) {
		return;
	}
	$post = get_post();
	if ( ! $post || ! current_user_can( 'edit_post', $post->ID ) ) {
		return;
	}
	wp_register_script( 'gogh-compose', plugins_url( 'gogh-compose.js', __FILE__ ), array(), '0.99.201-chrome', true );
	wp_enqueue_script( 'gogh-write', plugins_url( 'gogh-write.js', __FILE__ ), array( 'gogh-compose' ), '0.99.201-chrome', true );
	wp_enqueue_style( 'gogh-write', plugins_url( 'gogh-write.css', __FILE__ ), array(), '0.99.201-chrome' );
	wp_localize_script( 'gogh-write', 'GOGHWRITE', array(
		'postId'  => $post->ID,
		'restUrl' => esc_url_raw( rest_url() ),
		'nonce'   => wp_create_nonce( 'wp_rest' ),
		'status'  => $post->post_status,
		'homeUrl' => esc_url_raw( home_url( '/' ) ),
		'adminEdit' => esc_url_raw( get_edit_post_link( $post->ID, 'raw' ) ),
	) );
	show_admin_bar( false );
} );

// menus heal themselves: trashing a page removes its links from every
// menu ("i deleted some pages and now the menu looks broken" — core
// leaves a hole where the dead link was). Untrash re-adds nothing; a
// restored page is one drag away in the nav editor.
add_action( 'trashed_post', function ( $post_id ) {
	$type = get_post_type( $post_id );
	if ( ! in_array( $type, array( 'page', 'post' ), true ) ) {
		return;
	}
	$navs = get_posts( array(
		'post_type'   => 'wp_navigation',
		'post_status' => 'publish',
		'numberposts' => 20,
	) );
	foreach ( $navs as $nav ) {
		if ( false === strpos( $nav->post_content, '"id":' . $post_id ) ) {
			continue;
		}
		$cleaned = preg_replace_callback(
			'/<!--\s*wp:navigation-link\s+({[\s\S]*?})\s*\/-->/',
			function ( $m ) use ( $post_id ) {
				$attrs = json_decode( $m[1], true );
				return ( is_array( $attrs ) && isset( $attrs['id'] ) && (int) $attrs['id'] === (int) $post_id ) ? '' : $m[0];
			},
			$nav->post_content
		);
		if ( null !== $cleaned && $cleaned !== $nav->post_content ) {
			wp_update_post( array( 'ID' => $nav->ID, 'post_content' => $cleaned ) );
		}
	}
} );

function gogh_starters() {
	$out = array();
	foreach ( glob( __DIR__ . '/starters/*/manifest.json' ) as $mf ) {
		$slug = basename( dirname( $mf ) );
		$m    = json_decode( file_get_contents( $mf ), true );
		if ( $m && ! empty( $m['pages'] ) ) {
			$m['slug']    = $slug;
			$out[ $slug ] = $m;
		}
	}
	return $out;
}
function gogh_starter_page_content( $slug, $pg ) {
	$file = __DIR__ . '/starters/' . $slug . '/' . basename( $pg['file'] );
	if ( ! is_readable( $file ) ) {
		return '';
	}
	return str_replace(
		array( '{{gogh_theme}}', '{{gogh_plugin}}' ),
		array( get_template_directory_uri(), untrailingslashit( plugins_url( '', __FILE__ ) ) ),
		file_get_contents( $file )
	);
}
add_action( 'init', function () {
	foreach ( gogh_starters() as $slug => $m ) {
		foreach ( $m['pages'] as $pg ) {
			$content = gogh_starter_page_content( $slug, $pg );
			if ( '' === $content ) {
				continue;
			}
			register_block_pattern( 'gogh-starter/' . $slug . '-' . $pg['slug'], array(
				'title'    => $m['name'] . ' — ' . $pg['title'],
				'inserter' => false,
				'content'  => $content,
			) );
		}
	}
} );
add_action( 'rest_api_init', function () {
	register_rest_route( 'gogh/v1', '/starter', array(
		'methods'             => 'POST',
		'permission_callback' => function () {
			return current_user_can( 'manage_options' );
		},
		'args'                => array( 'slug' => array( 'required' => true, 'type' => 'string' ) ),
		'callback'            => function ( $req ) {
			$starters = gogh_starters();
			$slug     = sanitize_key( $req['slug'] );
			if ( empty( $starters[ $slug ] ) ) {
				return new WP_Error( 'gogh_no_starter', __( 'Unknown site design.', 'gogh-editor' ), array( 'status' => 404 ) );
			}
			$m = $starters[ $slug ];
			// current pages step aside, restorably — never deleted
			$old = get_posts( array(
				'post_type'   => 'page',
				'post_status' => array( 'publish', 'draft', 'private', 'pending' ),
				'numberposts' => -1,
				'fields'      => 'ids',
			) );
			foreach ( $old as $oid ) {
				wp_trash_post( $oid );
			}
			$front = 0;
			$blog  = 0;
			$made  = array();
			foreach ( $m['pages'] as $pg ) {
				$id = wp_insert_post( array(
					'post_type'    => 'page',
					'post_status'  => 'publish',
					'post_title'   => $pg['title'],
					'post_name'    => $pg['slug'],
					// wp_insert_post unslashes its input — without wp_slash it strips
					// the backslashes from the JSON < / " / - escapes in
					// the gogh/section model, so a widget's whtml became literal
					// "u003cdiv…" text in the editor ("issues with the blueprint")
					'post_content' => wp_slash( gogh_starter_page_content( $slug, $pg ) ),
					'meta_input'   => empty( $pg['template'] ) ? array()
						: array( '_wp_page_template' => sanitize_key( $pg['template'] ) ),
				) );
				if ( ! $id || is_wp_error( $id ) ) {
					continue;
				}
				$made[] = array(
					'id'      => $id,
					'title'   => $pg['title'],
					'no_menu' => isset( $pg['menu'] ) && false === $pg['menu'],
				);
				if ( ! empty( $pg['front'] ) ) {
					$front = $id;
				}
				if ( ! empty( $pg['blog'] ) ) {
					$blog = $id;
				}
			}
			if ( ! $made ) {
				return new WP_Error( 'gogh_starter_failed', __( 'The site design could not be applied.', 'gogh-editor' ), array( 'status' => 500 ) );
			}
			// starter posts: the notebook arrives lived-in, and gogh write
			// has a finished example on the shelf
			if ( ! empty( $m['posts'] ) ) {
				foreach ( $m['posts'] as $ps ) {
					$pid = wp_insert_post( array(
						'post_type'    => 'post',
						'post_status'  => 'publish',
						'post_title'   => $ps['title'],
						'post_name'    => $ps['slug'],
						'post_content' => wp_slash( gogh_starter_page_content( $slug, $ps ) ), // see the page insert above
					) );
					if ( $pid && ! is_wp_error( $pid ) && ! empty( $ps['category'] ) ) {
						$term = term_exists( $ps['category'], 'category' );
						if ( ! $term ) {
							$term = wp_insert_term( $ps['category'], 'category' );
						}
						if ( $term && ! is_wp_error( $term ) ) {
							$tid = is_array( $term ) ? (int) $term['term_id'] : (int) $term;
							wp_set_post_terms( $pid, array( $tid ), 'category' );
						}
					}
				}
			}
			$links = '';
			foreach ( $made as $c ) {
				if ( ! empty( $c['no_menu'] ) ) {
					continue;
				}
				$links .= '<!-- wp:navigation-link {"label":"' . esc_attr( $c['title'] ) . '","type":"page","id":' . $c['id'] .
					',"url":"' . esc_url( get_permalink( $c['id'] ) ) . '","kind":"post-type"} /-->';
			}
			// re-use a same-named menu rather than minting a new wp_navigation
			// post on every apply — otherwise re-running a starter litters the
			// "swap menus" list with a fresh "Café menu" each time
			$nav_title = $m['name'] . ' menu';
			$found = new WP_Query( array(
				'post_type'      => 'wp_navigation',
				'post_status'    => 'publish',
				'title'          => $nav_title,
				'posts_per_page' => 1,
				'fields'         => 'ids',
				'no_found_rows'  => true,
			) );
			$nav_id = $found->posts ? (int) $found->posts[0] : 0;
			if ( $nav_id ) {
				wp_update_post( array( 'ID' => $nav_id, 'post_content' => $links ) );
			} else {
				$nav_id = wp_insert_post( array(
					'post_type'    => 'wp_navigation',
					'post_status'  => 'publish',
					'post_title'   => $nav_title,
					'post_content' => $links,
				) );
			}
			// point the live header's menu at the new navigation
			$part = get_block_template( get_stylesheet() . '//header', 'wp_template_part' );
			if ( $part && $nav_id && ! is_wp_error( $nav_id ) ) {
				$praw = (string) $part->content;
				// a starter may choose one of gogh's own headers — the Yellow
				// House floats the transparent overlay over its hero
				if ( ! empty( $m['chrome']['header'] ) ) {
					$pfile = __DIR__ . '/patterns/' . sanitize_file_name( $m['chrome']['header'] ) . '.html';
					if ( is_readable( $pfile ) ) {
						$praw = file_get_contents( $pfile );
					}
				}
				$next = '';
				if ( preg_match( '/wp:navigation[^>]*"ref":\d+/', $praw ) ) {
					$next = preg_replace( '/("ref":)\d+/', '${1}' . $nav_id, $praw, 1 );
				} elseif ( preg_match( '/<!--\s+wp:navigation\s+\{/', $praw ) ) {
					$next = preg_replace( '/(<!--\s+wp:navigation\s+\{)/', '${1}"ref":' . $nav_id . ',', $praw, 1 );
				} else {
					$next = preg_replace( '/(<!--\s+wp:navigation)(\s+-->)/', '${1} {"ref":' . $nav_id . '}${2}', $praw, 1 );
				}
				if ( $next && $next !== $praw ) {
					if ( ! empty( $part->wp_id ) ) {
						wp_update_post( array( 'ID' => $part->wp_id, 'post_content' => $next ) );
					} else {
						$pid = wp_insert_post( array(
							'post_type'    => 'wp_template_part',
							'post_status'  => 'publish',
							'post_title'   => 'header',
							'post_name'    => 'header',
							'post_content' => $next,
						) );
						if ( $pid && ! is_wp_error( $pid ) ) {
							wp_set_post_terms( $pid, array( get_stylesheet() ), 'wp_theme' );
							wp_set_post_terms( $pid, array( 'header' ), 'wp_template_part_area' );
						}
					}
				}
			}
			// a starter may carry a bespoke PALETTE: theme palette slugs are
			// re-coloured (base/contrast keep roles, accents cycle), applied
			// as user global styles — same mechanism as Your brand
			if ( ! empty( $m['palette'] ) && class_exists( 'WP_Theme_JSON_Resolver' ) ) {
				$theme_pal = wp_get_global_settings( array( 'color', 'palette', 'theme' ) );
				if ( is_array( $theme_pal ) && $theme_pal ) {
					$pal     = $m['palette'];
					$accents = isset( $pal['accents'] ) && is_array( $pal['accents'] ) ? array_values( $pal['accents'] ) : array();
					$ai      = 0;
					$out_pal = array();
					foreach ( $theme_pal as $entry ) {
						$slug = isset( $entry['slug'] ) ? $entry['slug'] : '';
						if ( ( 'base' === $slug || 'background' === $slug ) && ! empty( $pal['base'] ) ) {
							$entry['color'] = $pal['base'];
						} elseif ( ( 'contrast' === $slug || 'text' === $slug || 'foreground' === $slug ) && ! empty( $pal['contrast'] ) ) {
							$entry['color'] = $pal['contrast'];
						} elseif ( $accents && 0 === strpos( $slug, 'accent' ) ) {
							$entry['color'] = $accents[ $ai % count( $accents ) ];
							$ai++;
						}
						$out_pal[] = $entry;
					}
					$gs_id = WP_Theme_JSON_Resolver::get_user_global_styles_post_id();
					if ( $gs_id ) {
						wp_update_post( array(
							'ID'           => $gs_id,
							'post_content' => wp_json_encode( array(
								'version'                     => class_exists( 'WP_Theme_JSON' ) ? WP_Theme_JSON::LATEST_SCHEMA : 3,
								'isGlobalStylesUserThemeJSON' => true,
								'settings'                    => array( 'color' => array( 'palette' => array( 'theme' => $out_pal ) ) ),
								'styles'                      => new stdClass(),
							) ),
						) );
					}
				}
			}
			// the design brings its own look: apply the named theme style
			// variation to user global styles. The user's saved gogh brand is
			// untouched and can be re-applied from Your brand at any time.
			if ( ! empty( $m['variation'] ) && class_exists( 'WP_Theme_JSON_Resolver' ) ) {
				foreach ( WP_Theme_JSON_Resolver::get_style_variations() as $v ) {
					if ( isset( $v['title'] ) && 0 === strcasecmp( $v['title'], $m['variation'] ) ) {
						$gs_id = WP_Theme_JSON_Resolver::get_user_global_styles_post_id();
						if ( $gs_id ) {
							wp_update_post( array(
								'ID'           => $gs_id,
								'post_content' => wp_json_encode( array(
									'version'                     => class_exists( 'WP_Theme_JSON' ) ? WP_Theme_JSON::LATEST_SCHEMA : 3,
									'isGlobalStylesUserThemeJSON' => true,
									'settings'                    => isset( $v['settings'] ) ? $v['settings'] : new stdClass(),
									'styles'                      => isset( $v['styles'] ) ? $v['styles'] : new stdClass(),
								) ),
							) );
						}
						break;
					}
				}
			}
			// remember which style the site now wears — WP itself forgets the
			// variation's name the moment it's copied into user global styles
			update_option( 'gogh_active_style', ! empty( $m['variation'] ) ? $m['variation'] : '' );
