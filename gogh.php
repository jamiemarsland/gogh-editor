/**
 * SPIKE variant B: rebake. On every save — by anyone, including users whose
 * content KSES just filtered — regenerate the baked <style> inside each v3
 * section from its attributes. The plugin authors these bytes server-side,
 * so the saver's capabilities are irrelevant; deactivation keeps the look.
 * ADOPTED as production behaviour (variant B won the matrix): default ON,
 * gogh_rebake_enabled filter remains as the escape hatch.
 */
function gogh_rebake_post_data( $data ) {
	if ( ! apply_filters( 'gogh_rebake_enabled', true ) ) {
		return $data;
	}
	if ( empty( $data['post_content'] ) || false === strpos( $data['post_content'], 'wp:gogh/section' ) ) {
		return $data;
	}
	$content = wp_unslash( $data['post_content'] );
	$blocks  = parse_blocks( $content );
	$changed = false;
	foreach ( $blocks as &$b ) {
		if ( 'gogh/section' !== $b['blockName'] || empty( $b['attrs'] ) ) {
			continue;
		}
		$css = gogh_css_from_attrs( $b['attrs'] );
		if ( '' === $css || false !== strpos( (string) $b['innerHTML'], 'class="gogh-style"' ) ) {
			continue;
		}
		$style = '<style class="gogh-style">' . $css . '</style>';
		foreach ( array( 'innerHTML', 'innerContent' ) as $k ) {
			if ( 'innerContent' === $k ) {
				foreach ( $b['innerContent'] as &$chunk ) {
					if ( is_string( $chunk ) && false !== strpos( $chunk, 'wp-block-gogh-section' ) ) {
						$chunk   = gogh_sweep_css_residue( $chunk );
						$chunk   = preg_replace( '/(<div class="wp-block-gogh-section[^"]*">)/', '$1' . $style, $chunk, 1 );
						$changed = true;
						break;
					}
				}
			} else {
				$b[ $k ] = gogh_sweep_css_residue( (string) $b[ $k ] );
				$b[ $k ] = preg_replace( '/(<div class="wp-block-gogh-section[^"]*">)/', '$1' . $style, $b[ $k ], 1 );
			}
		}
	}
	unset( $b );
	if ( $changed ) {
		$data['post_content'] = wp_slash( serialize_blocks( $blocks ) );
	}
	return $data;
}
add_filter( 'wp_insert_post_data', 'gogh_rebake_post_data', 20 );

/**
 * Front-end editor: enqueue for users who can edit the current page.
 */
add_action( 'wp_enqueue_scripts', function () {
	if ( ! is_singular() ) {
		return;
	}
	$post      = get_post();
	$has_gogh  = $post && false !== strpos( $post->post_content, 'gogh-section' );
	// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only view toggle; editor assets are capability-gated below.
	$want_edit = isset( $_GET['gogh-edit'] );
	if ( ! $post || ( ! $has_gogh && ! $want_edit ) ) {
		return;
	}

	// for every visitor: neutralise theme spacing around gogh sections, even
	// on pages whose stored stylesheets predate this rule
	wp_register_style( 'gogh-base', false, array(), '0.97.13-chrome' );
	wp_enqueue_style( 'gogh-base' );
	wp_add_inline_style( 'gogh-base',
		// full-bleed sections use 100vw, which includes the scrollbar — once
		// a vertical scrollbar exists they overflow sideways and the canvas
		// wobbles left-right. Clip horizontal overflow at the root (clip, not
		// hidden: no new scroll container, inner scrollers unaffected).
		'html { overflow-x: clip; }' .
		'.gogh-wrap { margin-block: 0 !important; min-width: 100%; }' .
		'.entry-content:has(> .gogh-wrap) { margin-block: 0 !important; }' .
		// pages saved before this rule shipped: image placeholders must not
		// inherit theme Group padding
		'.gogh-section > .wp-block-group { padding: 0 !important; box-sizing: border-box; }' .
		'.gogh-section > * { box-sizing: border-box; }' .
		// pasted-HTML sections: full bleed with zero vertical margins for
		// every visitor — the theme's block-gap must not band between them
		'.gogh-section-html { box-sizing: border-box !important; width: 100vw !important; max-width: 100vw !important; margin-inline: calc(50% - 50vw) !important; margin-block: 0 !important; }'
	);

	if ( ! current_user_can( 'edit_post', $post->ID ) ) {
		return;
	}

	wp_enqueue_script( 'gogh-editor', plugins_url( 'gogh-editor.js', __FILE__ ), array(), '0.97.13-chrome', true );
	wp_enqueue_style( 'gogh-editor', plugins_url( 'gogh-editor.css', __FILE__ ), array(), '0.97.13-chrome' );

	// WebMCP bridge: the page registers its editing verbs as agent tools.
	// OPT-IN only — add ?gogh-mcp=1 for a demo session (or enable sitewide
	// via the gogh_webmcp_enabled filter). Keeps future WebMCP-speaking
	// agents from discovering publish-capable tools uninvited.
	// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only opt-in toggle; script is capability-gated above.
	if ( isset( $_GET['gogh-mcp'] ) || isset( $_GET['gogh-test'] ) || apply_filters( 'gogh_webmcp_enabled', false ) ) {
		wp_enqueue_script( 'gogh-webmcp', plugins_url( 'gogh-webmcp.js', __FILE__ ), array( 'gogh-editor' ), '0.97.13-chrome', true );
	}

	// regression suite: /page/?gogh-test (editors only, never saves)
	// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only toggle enqueuing a test script for capability-checked editors.
	if ( isset( $_GET['gogh-test'] ) ) {
		wp_enqueue_script( 'gogh-tests', plugins_url( 'gogh-tests.js', __FILE__ ), array( 'gogh-editor' ), '0.97.13-chrome', true );
	}

	$rest_base = ( 'page' === $post->post_type ) ? 'pages' : 'posts';
	wp_localize_script( 'gogh-editor', 'GOGH', array(
		'postId'   => $post->ID,
		'restUrl'  => rest_url( 'wp/v2/' . $rest_base . '/' . $post->ID ),
		'mediaUrl' => rest_url( 'wp/v2/media' ),
		'canUpload' => current_user_can( 'upload_files' ),
		'canExp'   => current_user_can( 'upload_files' ) && current_user_can( 'unfiltered_html' ),
		// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only labs toggle
		// Make freeform ships on by default; &gogh-experiments=0 is the kill-switch,
		// bare &gogh-experiments opts into future experimental features.
		'canConvert' => apply_filters( 'gogh_convert_enabled', ! isset( $_GET['gogh-experiments'] ) || '0' !== $_GET['gogh-experiments'] ),
		// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only labs toggle
		'experiments' => isset( $_GET['gogh-test'] ) || ( isset( $_GET['gogh-experiments'] ) && '0' !== $_GET['gogh-experiments'] ),
		'brand'    => get_option( 'gogh_brand', null ) ?: null,
		'pageTemplate'  => get_page_template_slug( $post ) ?: '',
		'pageTemplates' => (function () use ( $post ) {
			$out = array();
			// includes gogh's registered Blank canvas (as 'blank-canvas') on WP 6.7+
			foreach ( (array) wp_get_theme()->get_page_templates( $post ) as $slug => $title ) {
				$out[] = array( 'slug' => (string) $slug, 'title' => (string) $title );
			}
			return $out;
		})(),
		'modified' => get_post_modified_time( 'Y-m-d\TH:i:s', true, $post ),
		'theme'    => get_stylesheet(),
		'themeName' => wp_get_theme()->get( 'Name' ),
		'gsId'     => ( class_exists( 'WP_Theme_JSON_Resolver' ) && current_user_can( 'edit_theme_options' ) )
			? WP_Theme_JSON_Resolver::get_user_global_styles_post_id() : 0,
		'palette'  => array_values( array_map(
			function ( $c ) { return array( 'slug' => $c['slug'] ); },
			(array) ( wp_get_global_settings( array( 'color', 'palette' ) )['theme'] ?? array() )
		) ),
		'nonce'    => wp_create_nonce( 'wp_rest' ),
	) );
} );

/**
 * Live-preview renderer: the core block-renderer returns bare markup with
 * none of the per-instance layout CSS (nav flex rules, container gaps), so
 * header/footer previews looked broken. This renders markup the way a real
 * page does and returns the generated styles + the block stylesheets the
 * markup needs.
 */
add_action( 'rest_api_init', function () {
	register_rest_route( 'gogh/v1', '/render', array(
		'methods'             => 'POST',
		'permission_callback' => function () {
			return current_user_can( 'edit_posts' );
		},
		'callback'            => function ( $req ) {
			$content = (string) $req->get_param( 'content' );
			$html    = do_blocks( $content );
			$css     = function_exists( 'wp_style_engine_get_stylesheet_from_context' )
				? (string) wp_style_engine_get_stylesheet_from_context( 'block-supports' )
				: '';
			$hrefs = array();
			$walk  = function ( $blocks ) use ( &$walk, &$hrefs ) {
				foreach ( $blocks as $b ) {
					if ( ! empty( $b['blockName'] ) ) {
						$bt = WP_Block_Type_Registry::get_instance()->get_registered( $b['blockName'] );
						if ( $bt ) {
							foreach ( (array) $bt->style_handles as $h ) {
								if ( $h && wp_style_is( $h, 'registered' ) ) {
									$obj = wp_styles()->registered[ $h ];
									if ( ! empty( $obj->src ) ) {
										$src = ( 0 === strpos( $obj->src, 'http' ) ) ? $obj->src : site_url( $obj->src );
										$hrefs[ $h ] = add_query_arg( 'ver', $obj->ver ? $obj->ver : get_bloginfo( 'version' ), $src );
									}
								}
							}
						}
					}
					if ( ! empty( $b['innerBlocks'] ) ) {
						$walk( $b['innerBlocks'] );
					}
				}
			};
			$walk( parse_blocks( $content ) );
			return array(
				'html'   => $html,
				'css'    => $css,
				'styles' => array_values( $hrefs ),
			);
		},
	) );
} );

